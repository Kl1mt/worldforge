/**
 * The substitutions for a look on a class, or `null` when the look changes nothing
 * (`appearance.default`, or an id this build does not know: draw the plain art).
 */
export function heroPaletteSwaps(
  appearanceId: string,
  classId: ClassId,
): readonly ColourSwap[] | null {
  if (!appearanceId.startsWith('appearance.')) return null;
  const id = appearanceId.slice('appearance.'.length);
  if (!(HERO_PALETTE_IDS as readonly string[]).includes(id)) return null;
  return HERO_PALETTE_SWAPS[id as HeroPaletteId][classId] ?? null;
}

const packHex = (hex: string): number => Number.parseInt(hex.slice(1), 16);

/**
 * Pure: a copy of RGBA `pixels` (e.g. `ImageData.data`) with every opaque pixel whose colour is a
 * swap's source replaced by its target. Alpha and every other pixel are untouched.
 */
export function recolourPixels(
  pixels: Uint8ClampedArray | Uint8Array,
  swaps: readonly ColourSwap[],
): Uint8ClampedArray {
  const map = new Map<number, number>(swaps.map(([from, to]) => [packHex(from), packHex(to)]));
  const out = new Uint8ClampedArray(pixels);
  for (let i = 0; i < out.length; i += 4) {
    if (out[i + 3] === 0) continue;
    const to = map.get((out[i]! << 16) | (out[i + 1]! << 8) | out[i + 2]!);
    if (to === undefined) continue;
    out[i] = (to >> 16) & 0xff;
    out[i + 1] = (to >> 8) & 0xff;
    out[i + 2] = to & 0xff;
  }
  return out;
}

const recoloured = new Map<string, Promise<string>>();

/**
 * Browser only: an object URL of `sprite` (a class portrait or its attack sheet) in a look, made
 * once and cached. Resolves to the sprite's own path for the default look; draw the result like
 * the sprite (same size, frames and integer scale). Rejects if the image fails to load, so the
 * caller can fall back to the plain art.
 */
export function recolouredSpriteUrl(
  sprite: SpriteAsset,
  classId: ClassId,
  appearanceId: string,
): Promise<string> {
  const swaps = heroPaletteSwaps(appearanceId, classId);
  if (!swaps) return Promise.resolve(sprite.path);
  const key = `${sprite.path}|${appearanceId}`;
  let url = recoloured.get(key);
  if (!url) {
    url = new Promise<string>((resolve, reject) => {
      const img = new Image();
      img.onload = () => {
        const canvas = document.createElement('canvas');
        canvas.width = img.naturalWidth;
        canvas.height = img.naturalHeight;
        const ctx = canvas.getContext('2d');
        if (!ctx) return reject(new Error('no 2d canvas'));
        ctx.imageSmoothingEnabled = false;
        ctx.drawImage(img, 0, 0);
        const data = ctx.getImageData(0, 0, canvas.width, canvas.height);
        data.data.set(recolourPixels(data.data, swaps));
        ctx.putImageData(data, 0, 0);
        canvas.toBlob((blob) =>
          blob ? resolve(URL.createObjectURL(blob)) : reject(new Error('toBlob failed')),
        );
      };
      img.onerror = () => reject(new Error(`failed to load ${sprite.path}`));
      img.src = sprite.path;
    });
    url.catch(() => recoloured.delete(key));
    recoloured.set(key, url);
  }
  return url;
}
