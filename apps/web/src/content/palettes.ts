/**
 * Hero appearance palettes (art ticket A.13, the collection book is ticket 6.8). Each look is a
 * palette swap of the class art: per class, a list of exact source colour → target colour
 * substitutions that covers the portrait, the code idle (which moves the portrait) and the
 * 8-frame attack sheet (A.14 snapped its frames to the portrait's own colours, so one list
 * covers both). `appearance.default` changes nothing.
 *
 * **Runtime, not baked.** The swap is applied in the browser on a canvas (`recolourPixels`,
 * `recolouredSpriteUrl`) rather than shipped as 32 recoloured PNGs. A sheet is at most 1024×128
 * pixels and a swap is one lookup per pixel, done once per (sheet, look) and cached as an object
 * URL, so the render cost is a one-off of about a millisecond; baking would add ~0.5 MB of near-
 * duplicate art per class and a re-bake whenever a sprite or a palette is touched. Pixels whose
 * colour is not in the list (the outline, skin, bone) are left exactly as they are.
 *
 * The data block below is generated by `python3 tools/art/hero_palettes.py --write` (roles per
 * colour, theme hues, luma kept) and checked by `palettes.test.ts` against the PNGs.
 */

